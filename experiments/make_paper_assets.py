def tab_calibration_full() -> str:
    from scipy.stats import beta as _beta
    cal = _load("draw_count_calibration.json")
    trials = cal["rows"][0]["trials"]

    def _cp_up(rate, n, conf=0.95):
        """95% Clopper--Pearson upper bound; exact one-event form when k==0."""
        k = round(rate * n)
        a = (1 - conf) / 2
        return (1 - a ** (1.0 / n)) if k == 0 else float(_beta.ppf(1 - a, k + 1, n - k))

    rows = "\n".join(
        f"{r['n_draws']:>5} & {r['naive_false_positive_rate']*100:.1f}\\% & "
        f"{r['corrected_per_item_false_positive_rate']*100:.2f}\\% "
        f"[{_cp_up(r['corrected_per_item_false_positive_rate'], trials)*100:.2f}] & "
        f"{r['corrected_familywise_false_positive_rate']*100:.2f}\\% "
        f"[{_cp_up(r['corrected_familywise_false_positive_rate'], trials)*100:.2f}] \\\\"
        for r in cal["rows"])
    return f"""% GENERATED by make_paper_assets.py -- do not edit by hand.
\\begin{{table}}[h]
\\centering
\\small
\\begin{{tabular}}{{rrrr}}
\\toprule
Draws & Naive & Corrected & Corrected \\\\
per cond. & plug-in & (per-item) & (family-wise) \\\\
\\midrule
{rows}
\\bottomrule
\\end{{tabular}}
\\caption{{False-positive rate of the compatibility certificate under a null with one
shared answer law and answer-independent per-condition disclosure, both resampled
from the real full-panel distributions ({cal['disclosure_pool_size']:,} disclosure and
{cal['occshare_pool_size']:,} answer-share observations), so every rejection is spurious by
construction. {trials:,} replications per row, $Z{{=}}3$, $K{{=}}2$. The per-item
regime targets $\\alpha{{=}}0.05$; the family-wise regime targets $\\alpha{{=}}0.05/{cal['items_per_screen_for_familywise']}$,
dividing $\\alpha$ by the {cal['items_per_screen_for_familywise']} items on the screen. Bracketed values are 95\\%
Clopper--Pearson upper bounds over the {trials:,} replications; these are empirical
Monte Carlo rates, distinct from the nominal $\\alpha$ each regime targets.}}
\\label{{tab:calibration}}
\\end{{table}}
""".replace(f"{cal['disclosure_pool_size']:,}", f"{cal['disclosure_pool_size']:,}".replace(",", "{,}")
    ).replace(f"{cal['occshare_pool_size']:,}", f"{cal['occshare_pool_size']:,}".replace(",", "{,}")
    ).replace(f"{trials:,} replications", f"{trials:,} replications".replace(",", "{,}"))


