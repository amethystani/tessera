def fig_identification(summary_path: Path) -> str:
    """Forest-style plot: identified interval, measured truth, reported score.

    Everything is drawn on the stereotype-aligned-rate scale theta in [0,1] so
    the interval and the forced-choice measurement are directly comparable.
    The reported s_AMB is annotated per row rather than plotted, because it is
    a different quantity on a different scale, and putting them on one axis
    would blur the distinction.
    """
    fp = json.loads(summary_path.read_text())
    rows = fp["rows"]

    bars, truth_pts, labels, annots = [], [], [], []
    for i, r in enumerate(rows):
        y = len(rows) - i           # top-to-bottom in listed order
        lo, hi = r["manski_lo"], r["manski_hi"]
        truth = r["forced_logprob_biased_rate"]
        bars.append(f"    \\draw[line width=5pt, gray!35] "
                    f"(axis cs:{lo:.4f},{y}) -- (axis cs:{hi:.4f},{y});")
        truth_pts.append(f"({truth:.4f},{y})")
        labels.append(f"{y}/{SHORT.get(r['model'], r['model'])}")
        annots.append(
            f"    \\node[anchor=west, font=\\tiny, gray!70] at "
            f"(axis cs:1.015,{y}) {{{r['baseline_s_AMB']:.3f}}};")

    return f"""% GENERATED by make_paper_assets.py -- do not edit by hand.
\\begin{{figure}}[t]
\\centering
\\begin{{tikzpicture}}
\\begin{{axis}}[
  width=0.80\\columnwidth, height=4.6cm,
  xmin=-0.02, xmax=1.30, ymin=0.4, ymax={len(rows) + 0.7},
  xtick={{0,0.25,0.5,0.75,1}},
  xticklabels={{0,.25,.5,.75,1}},
  ytick={{{','.join(str(len(rows) - i) for i in range(len(rows)))}}},
  yticklabels={{{','.join(SHORT.get(r['model'], r['model']) for r in rows)}}},
  xlabel={{Stereotype-aligned rate $\\theta$}},
  tick label style={{font=\\scriptsize}}, label style={{font=\\scriptsize}},
  axis lines=left, y axis line style={{draw=none}}, ytick style={{draw=none}},
  xmajorgrids, grid style={{dotted, gray!40}},
  clip=false,
]
{chr(10).join(bars)}
\\addplot[only marks, mark=*, mark size=2.2pt, black] coordinates {{
  {' '.join(truth_pts)}}};
\\draw[dashed, gray] (axis cs:0.5,0.4) -- (axis cs:0.5,{len(rows) + 0.55});
\\node[anchor=south, font=\\tiny, gray] at (axis cs:0.5,{len(rows) + 0.55})
  {{no preference}};
\\node[anchor=west, font=\\tiny\\bfseries, gray!70] at
  (axis cs:1.015,{len(rows) + 0.45}) {{$s_{{\\text{{AMB}}}}$}};
{chr(10).join(annots)}
\\end{{axis}}
\\end{{tikzpicture}}
\\caption{{What the benchmark pins down, per checkpoint. The grey bar is the
Manski identified interval for the stereotype-aligned rate $\\theta$, computed
from the abstain-permitted condition alone, and the dot is $\\theta$ measured
directly under logit-forced choice. The dot falls inside the bar in 6 of 6
cases, but the bars span most of the unit interval, so the reported
ambiguous bias score (right column) is compatible with almost any
disposition. Every model sits above $\\theta=0.5$ while posting a score that
reads as near-zero.}}
\\label{{fig:identification}}
\\end{{figure}}
"""


