        if path.name in APPENDIX_HERE:
            # appendix floats sit under their own heading instead of drifting
            text = text.replace("\\begin{table}[t]", "\\begin{table}[H]", 1).replace(
                "\\begin{figure}[t]", "\\begin{figure}[H]", 1)
        path.write_text(text)
